#include <unistd.h>

int	ft_strcmp(char *s1, char *s2)
{
	int	i;
	int	a;

	i = 0;
	while (s1[i] != '\0' || s2[i] != '\0')
	{
		if (s1[i] != s2[i])
		{
			a = s1[i] - s2[i];
			break ;
		}
		else
			a = s1[i] - s2[i];
		i++;
	}
	return (a);
}
